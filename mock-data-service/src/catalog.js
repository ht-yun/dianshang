/**
 * 商品词与其专属卖点，用「商品词|卖点1,卖点2,卖点3」的紧凑格式维护，
 * 模块加载时解析成 { n: 商品词, a: [卖点] }，比嵌套对象更易读易改。
 */
function parseItems(rows) {
  return rows.map((row) => {
    const [n, attrs] = row.split('|');
    return { n, a: attrs.split(',') };
  });
}

